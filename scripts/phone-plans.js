// Generates packages/lib/src/constants/phone-plans.ts from libphonenumber-js metadata.
// Only keeps what the phone input needs before the full library has loaded: calling code,
// national (trunk) prefix and the possible lengths of the national number.
import { writeFileSync } from 'node:fs';
import { Metadata } from 'libphonenumber-js/core';
import metadata from 'libphonenumber-js/min/metadata';

const output = 'packages/lib/src/constants/phone-plans.ts';
const m = new Metadata(metadata);

const plans = {};
for (const country of Object.keys(metadata.countries).sort()) {
  m.selectNumberingPlan(country);
  const plan = m.numberingPlan;
  const nationalPrefix = plan.nationalPrefix();
  plans[country] = [
    plan.callingCode(),
    typeof nationalPrefix === 'string' ? nationalPrefix : '',
    plan.possibleLengths()
  ];
}

writeFileSync(
  output,
  `// Generated by scripts/phone-plans.js - do not edit by hand.

// [calling code, national prefix, possible national number lengths]
export const phonePlans: Record<string, [string, string, number[]]> = ${JSON.stringify(plans)};
`
);
console.info(`Wrote ${Object.keys(plans).length} numbering plans to ${output}`);
